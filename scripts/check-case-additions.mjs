import assert from 'node:assert/strict';
import { boardClaims, normalizeBoard, placeOnBoard, boardReady, reviewBoard } from '../src/game/cases/case05-board.ts';
import { communityReactions } from '../src/game/cases/case06-epilogue.ts';
let draft = normalizeBoard(undefined);
assert.equal(boardReady(draft), false);
assert.equal(normalizeBoard({ checked: true, placements: {} }).checked, false);
for (const c of boardClaims) draft = placeOnBoard(draft, c.id, { category: c.category, evidenceId: c.evidenceId });
assert.equal(boardReady(draft), true);
assert(reviewBoard(draft).every(r => r.categoryCorrect && r.evidenceCorrect));
draft = normalizeBoard({ ...draft, checked: true });
assert.equal(draft.checked, true);
assert.deepEqual(normalizeBoard(JSON.parse(JSON.stringify(draft))), draft);
draft = placeOnBoard(draft, 'change', { category: 'unsupported' });
assert.equal(draft.checked, false);
assert.equal(reviewBoard(draft)[0].categoryCorrect, false);
assert.equal(normalizeBoard({ placements: { change: { category: 'bad', evidenceId: 'E6-D' } }, checked: true }).checked, false);
const good = communityReactions(['company', 'residents', 'foreign', 'reach', 'protect']);
assert.equal(good.length, 4);
assert(good[0].message.includes('διαφωνούμε'));
const mixed = communityReactions(['company', 'nobody', 'all23', 'residents', 'sponsor', 'foreign', 'address', 'protect']);
assert(mixed[0].message.includes('23'));
assert(mixed[1].message.includes('πληρωμή'));
assert(mixed[2].message.includes('αναδημοσιευτούν'));
assert(mixed[3].message.includes('καμία ευθύνη'));
const missing = communityReactions([]);
assert(missing[2].note.includes('Δεν υποθέτουμε'));
console.log('Board persistence, review gating, revisions and epilogue branches passed.');
