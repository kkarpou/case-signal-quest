import assert from 'node:assert/strict';
import { ensureCheckin, readExperience, updateCheckin, experienceCSV } from '../src/game/experience-data.ts';
let seq = 0;
const uuid = () => `id-${++seq}`;
const now = '2026-10-09T17:00:00Z';
let { log, record } = ensureCheckin(readExperience({ getItem: () => null }), 'case01', 'session-1', uuid, now);
assert.equal(record.status, 'presented');
assert.deepEqual(record.answers, {});
assert.equal(ensureCheckin(log, 'case01', 'session-2', uuid, now).record.id, record.id);
log = updateCheckin(log, record.id, { enjoyment: 3 }, 'presented', now);
assert.equal(readExperience({ getItem: () => JSON.stringify(log) }).records[0].answers.enjoyment, 3);
assert.throws(() => updateCheckin(log, record.id, { enjoyment: 3 }, 'submitted', now));
log = updateCheckin(log, record.id, { enjoyment: 3, difficulty: 5, clarity: 2 }, 'submitted', now);
const finalized = log.records[0];
log = updateCheckin(log, record.id, {}, 'skipped', now);
assert.deepEqual(log.records[0], finalized);
const next = ensureCheckin({ ...log, attempts: { case01: 'new-attempt' } }, 'case01', 'session-2', uuid, now);
assert.equal(next.log.records.length, 2);
const skipped = updateCheckin(next.log, next.record.id, { enjoyment: 1 }, 'skipped', now);
assert.deepEqual(skipped.records[1].answers, {});
assert.equal(skipped.records[0].sessionId, 'session-1');
assert.equal(experienceCSV(skipped.records).split('\r\n').length, 3);
assert.throws(() => readExperience({ getItem: () => '{bad' }));
assert.throws(() => readExperience({ getItem: () => JSON.stringify({ ...log, records: [{ ...finalized, answers: { enjoyment: 7 } }] }) }));
console.log('Experience lifecycle checks passed.');
